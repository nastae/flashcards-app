CREATE TABLE quiz_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
--    user_id VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS',
    total_questions INT NOT NULL,
    current_question_number INT NOT NULL DEFAULT 1,
    correct_answers INT NOT NULL DEFAULT 0,
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,

    CONSTRAINT fk_quiz_session_group
        FOREIGN KEY (group_id) REFERENCES groups(id)
);

CREATE TABLE quiz_session_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_session_id BIGINT NOT NULL,
    flashcard_id BIGINT NOT NULL,
    question_number INT NOT NULL,

    CONSTRAINT fk_quiz_question_session
        FOREIGN KEY (quiz_session_id) REFERENCES quiz_sessions(id),
    CONSTRAINT fk_quiz_question_flashcard
        FOREIGN KEY (flashcard_id) REFERENCES flashcards(id),
    CONSTRAINT uk_quiz_session_question_number
        UNIQUE (quiz_session_id, question_number),
    CONSTRAINT uk_quiz_sessions_flashcard
        UNIQUE (quiz_session_id, flashcard_id)
);

CREATE TABLE quiz_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_session_question_id BIGINT NOT NULL,
    selected_flashcard_id BIGINT NOT NULL,
    is_correct BOOLEAN NOT NULL,
    answered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_quiz_answer_question
        UNIQUE (quiz_session_question_id),
    CONSTRAINT fk_quiz_answer_question
        FOREIGN KEY (quiz_session_question_id)
        REFERENCES quiz_session_questions(id),
    CONSTRAINT fk_quiz_answer_selected_flashcard
        FOREIGN KEY (selected_flashcard_id)
        REFERENCES flashcards(id)
);

CREATE INDEX idx_quiz_status
--    ON quiz_sessions(user_id, status);
    ON quiz_sessions(status);

