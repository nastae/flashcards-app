CREATE TABLE quiz_question_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_session_question_id BIGINT NOT NULL,
    flashcard_id BIGINT NOT NULL,
    option_text VARCHAR(255) NOT NULL,

    CONSTRAINT fk_quiz_option_question
        FOREIGN KEY (quiz_session_question_id)
        REFERENCES quiz_session_questions(id),
    CONSTRAINT fk_quiz_option_flashcard
        FOREIGN KEY (flashcard_id)
        REFERENCES flashcards(id),
    CONSTRAINT uk_quiz_question_option_card
        UNIQUE (quiz_session_question_id, flashcard_id)
);